
-- Implementation Waves: one permanent wave per store, independent of active status.
-- Existing stores (active AND inactive) are assigned to wave 1.
-- No financial or purchase/quote/work amount is rewritten.
create table if not exists public.implementation_waves (
  id integer generated by default as identity primary key,
  name text not null check (length(trim(name)) between 3 and 100),
  status text not null default 'planning'
    check (status in ('planning', 'in_progress', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.implementation_waves (id, name, status)
values (1, '1ª onda', 'in_progress')
on conflict (id) do nothing;

select setval(
  pg_get_serial_sequence('public.implementation_waves', 'id'),
  greatest((select max(id) from public.implementation_waves), 1)
);

alter table public.lojas
  add column if not exists wave_id integer
    references public.implementation_waves(id) on delete restrict;

-- Historical stores, including inactive ones, are wave 1.
update public.lojas set wave_id = 1 where wave_id is null;
alter table public.lojas alter column wave_id set not null;

create index if not exists lojas_wave_id_idx on public.lojas (wave_id, id);
create index if not exists supply_quote_stores_store_wave_scope_idx
  on public.supply_quote_stores (store_id, quote_id);
create index if not exists supply_purchase_stores_store_wave_scope_idx
  on public.supply_purchase_stores (store_id, purchase_id);
create index if not exists works_services_store_wave_scope_idx
  on public.works_services (store_id, id);
create index if not exists store_needs_store_wave_scope_idx
  on public.store_needs (store_id, id);

create trigger implementation_waves_updated_at
before update on public.implementation_waves
for each row execute function app.set_updated_at();

alter table public.implementation_waves enable row level security;
create policy implementation_waves_select on public.implementation_waves
for select to authenticated
using (app.current_usuario_id() is not null);
create policy implementation_waves_admin_insert on public.implementation_waves
for insert to authenticated
with check (app.can('stores', 'create'));
create policy implementation_waves_admin_update on public.implementation_waves
for update to authenticated
using (app.can('access', 'view'))
with check (app.can('access', 'view'));

revoke all on public.implementation_waves from anon, authenticated;
grant select, insert, update on public.implementation_waves to authenticated;
grant usage, select on sequence public.implementation_waves_id_seq to authenticated;
grant all on public.implementation_waves to service_role;
grant usage, select on sequence public.implementation_waves_id_seq to service_role;

-- Wave reassignment audit protects historical provenance.
create or replace function private.audit_loja_wave_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if old.wave_id is distinct from new.wave_id then
    insert into public.audit_logs (
      actor_usuario_id, action, entity_type, entity_id, before_json, after_json, origin
    ) values (
      app.current_usuario_id(), 'store.wave_changed', 'loja', new.id,
      jsonb_build_object('code', old.codigo_negocio, 'wave_id', old.wave_id),
      jsonb_build_object('code', new.codigo_negocio, 'wave_id', new.wave_id),
      'database'
    );
  end if;
  return new;
end
$fn$;

create trigger loja_wave_change_audit
after update of wave_id on public.lojas
for each row execute function private.audit_loja_wave_change();

comment on column public.lojas.wave_id is
  'Permanent implantation wave; existing active/inactive stores were classified as wave 1.';
